// using enums for the menu to have a clear code, the enum has different status for each choice chosen by the user
enum MenuChoice {
    DISPLAY= 1,   //1 to display the board
    LOAD,         //2 to load the board from a file
    EDITLIST,    //3 to edit the list using linked lists
    EDITBOARD,   //4 to edit the board
    SAVE,        //5 to save to a file
    QUIT ,      //to quit the program - clear the screen
};

int main(void) {

    printf("==================================================\n");
    printf("||                                              ||\n");
    printf("||      WELCOME TO THE KANBAN BOARD GENERATOR   ||\n");
    printf("||                                              ||\n");
    printf("==================================================\n\n");

    //creating the start list and passing it to the function that creates the full linked list
    List *list1=malloc(sizeof(List));
    //calling a function that initializes the lists and their corresponding items by using structs to create linked lists
    createLinkedList(list1);
    display(list1);

    while (1) {
    printf("MENU:\n 1.Display Board\n 2.Load Board from a file\n 3.Edit List\n 4.Edit Board\n 5.Save Board to a file\n 6.Quit\n");
        //Assume the value of current choice is always unknown unless entered a valid operation
        enum MenuChoice choice;
        choice =7; //setting the choice to be a value that will go straight away to default this way if the user enters an invalid input the choice will go to default
        //otherwise choice will remain the previously used number since scanf will not be able to read the invalid input - by setting choice to be a value that is not recognazied we ensure that it will always go to default unless a valid input is entered by the user

        scanf("%d",&choice);
        //clear new line character after scanf from the menu - before using fgets in the functions bellow that take in a string from the user as the name for a list or an item
        int c;
        while ( (c=getchar()) != '\n'  && c  != EOF);

        switch (choice) {
            case DISPLAY:
                display(list1);
                break;
            case LOAD:
                 loadBoard(&list1);
                break;
            case EDITLIST:
                menuEditItem(list1);
                break;
            case EDITBOARD:
                menuEditBoard(&list1); // & needed to send address of pointer
                break;
            case SAVE:
                saveBoard(list1);
                break;
            case QUIT:
                quit(list1);
                break;
            default:  //if no valid operation was entered by the user the status remains unknown and will print a message
                printf("Command not recognized\n");
                break;
        }
    }

    return 0;
}

